import * as path from 'path';
import type {
  DataPlan,
  GeneratedScript,
  TestCase,
} from '../../lifecycle/testingArtifactSchemas.js';

export interface GeneratePytestScriptInput {
  caseSet: TestCase;
  dataPlan?: DataPlan;
  workflowInstanceId?: string;
  sourceNodeId?: string;
  generatedAt?: number;
}

export function renderTemplate(template: string, context: Record<string, unknown>): string {
  return template.replace(/\{\{\s*([a-zA-Z_.][\w.]*)\s*\}\}/g, (_, expression: string) => {
    const value = lookupTemplateValue(expression, context);
    return value === undefined || value === null ? `{{${expression}}}` : String(value);
  });
}

export function generatePytestScripts(input: GeneratePytestScriptInput): GeneratedScript[] {
  return input.caseSet.cases.map(testCase => {
    const fileName = `test_${safePythonName(testCase.title || testCase.testCaseId)}.py`;
    const scriptId = `script-${testCase.testCaseId}`;
    const content = renderPytestContent({
      requirementId: input.caseSet.requirementId,
      testCase,
      dataPlan: input.dataPlan,
    });
    return {
      schemaVersion: 1,
      artifactKind: 'testing-generated-script',
      requirementId: input.caseSet.requirementId,
      runId: input.caseSet.runId,
      workflowInstanceId: input.workflowInstanceId ?? input.caseSet.workflowInstanceId,
      sourceNodeId: input.sourceNodeId ?? 'generate_scripts',
      status: 'draft',
      generatedAt: input.generatedAt ?? Date.now(),
      upstreamArtifactIds: [],
      scriptId,
      testCaseIds: [testCase.testCaseId],
      dataPlanId: input.dataPlan?.dataPlanId,
      language: 'python',
      path: path.posix.join('artifacts', 'testing', input.caseSet.workflowInstanceId, 'scripts', fileName),
      command: `pytest -q ${fileName}`,
      content,
      environmentRequirements: environmentRequirements(input.dataPlan),
    };
  });
}

function renderPytestContent(args: {
  requirementId: string;
  testCase: TestCase['cases'][number];
  dataPlan?: DataPlan;
}): string {
  const steps = args.testCase.steps.length
    ? args.testCase.steps
    : ['Execute the requirement flow under test.'];
  const dataSetupComments = args.dataPlan?.steps.map(step => `# data-step ${step.id}: ${step.description}`) ?? [];
  return [
    '# Generated by ai-coding Testing Management',
    `# requirementId: ${args.requirementId}`,
    `# testCaseId: ${args.testCase.testCaseId}`,
    `# dataPlanId: ${args.dataPlan?.dataPlanId ?? 'none'}`,
    'import os',
    'import pytest',
    '',
    ...dataSetupComments,
    '',
    `def test_${safePythonName(args.testCase.testCaseId)}():`,
    `    """${escapeDocstring(args.testCase.title)}"""`,
    '    base_url = os.getenv("TEST_BASE_URL", "http://localhost:8080")',
    '    assert base_url',
    ...steps.map((step, index) => `    # step ${index + 1}: ${step}`),
    `    expected = ${JSON.stringify(args.testCase.expectedResult || 'completed')}`,
    '    assert expected',
    '',
  ].join('\n');
}

function environmentRequirements(dataPlan: DataPlan | undefined): string[] {
  const appIds = new Set(dataPlan?.steps.flatMap(step => step.inputRef ? [step.inputRef] : []) ?? []);
  return ['pytest', 'TEST_BASE_URL', ...appIds];
}

function lookupTemplateValue(expression: string, context: Record<string, unknown>): unknown {
  if (expression.startsWith('faker.')) {
    return fakeValue(expression.slice('faker.'.length));
  }
  let current: unknown = context;
  for (const part of expression.split('.')) {
    if (current && typeof current === 'object' && part in current) {
      current = (current as Record<string, unknown>)[part];
    } else {
      return undefined;
    }
  }
  return current;
}

function fakeValue(kind: string): string | undefined {
  if (kind === 'email') return `test-${Math.random().toString(36).slice(2, 8)}@example.com`;
  if (kind === 'uuid') return `id-${Math.random().toString(36).slice(2, 10)}`;
  if (kind === 'phone') return `138${Math.floor(Math.random() * 1e8).toString().padStart(8, '0')}`;
  return undefined;
}

function safePythonName(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9_]+/g, '_').replace(/^_+|_+$/g, '') || 'generated_case';
}

function escapeDocstring(value: string): string {
  return value.replace(/"""/g, '\\"\\"\\"');
}
